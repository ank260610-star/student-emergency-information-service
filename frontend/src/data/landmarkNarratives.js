// A compact client-side retrieval layer for the curated landmark materials.
// It intentionally returns only one strongest match so the agent receives a
// precise context rather than a mixed, potentially contradictory dossier.
export function findLandmarkNarrative(text) {
  const normalizedText = String(text || '').toLocaleLowerCase('zh-CN').replace(/\s/g, '')
  if (!normalizedText) return null

  return Object.entries(landmarkNarratives)
    .flatMap(([id, narrative]) => [narrative.title, ...(landmarkSearchAliases[id] || [])]
      .map((alias) => ({
        id,
        narrative,
        index: normalizedText.lastIndexOf(alias.toLocaleLowerCase('zh-CN')),
        aliasLength: alias.length,
      }))
      .filter((match) => match.index >= 0))
    .sort((left, right) => right.aliasLength - left.aliasLength || right.index - left.index)[0]
    ?.narrative || null
}
